<#
.SYNOPSIS
  Writes site/data.js: the desk.json schema, the example config, the four themes and the offline sample data,
  copied verbatim so the static configurator never fetches anything. -Check compares instead of writing
  and exits 1 if site/data.js is out of date.
#>
[CmdletBinding()]
param([switch]$Check)
$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
function Raw([string]$rel) { return ([IO.File]::ReadAllText((Join-Path $repo $rel))).Trim() }
$themes = Get-ChildItem -Directory (Join-Path $repo 'themes') | Sort-Object Name |
    ForEach-Object { '    "{0}": {1}' -f $_.Name, (Raw "themes\$($_.Name)\theme.json") }
$np = (Raw 'examples\nowplaying.txt') -split "`r?`n"
$text = @"
// Generated by tools/build-site-data.ps1 from config/, themes/ and examples/. Do not edit by hand.
window.DESK_DATA = {
  "schema": $(Raw 'config\desk.schema.json'),
  "example": $(Raw 'config\desk.example.json'),
  "themes": {
$($themes -join ",`n")
  },
  "mock": {
    "weather": $(Raw 'examples\weather.json'),
    "prices": $(Raw 'examples\prices.json'),
    "status": $(Raw 'examples\status.json'),
    "nowplaying": { "song": "$($np[0])", "artist": "$($np[1])" }
  }
};
"@
$text = ($text -replace "`r`n", "`n") + "`n"
$out = Join-Path $repo 'site\data.js'
if ($Check) {
    $cur = if (Test-Path $out) { [IO.File]::ReadAllText($out) } else { '' }
    if ($cur -ne $text) { Write-Output 'ERROR  site/data.js is out of date: run tools\build-site-data.ps1'; exit 1 }
    Write-Output 'site data: up to date'; exit 0
}
[IO.File]::WriteAllText($out, $text, (New-Object Text.UTF8Encoding($false)))
Write-Output "wrote site/data.js"
